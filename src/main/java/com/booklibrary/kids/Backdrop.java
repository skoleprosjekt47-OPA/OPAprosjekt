/**
 * The kind of place a story page happens in. Each one is drawn and animated differently.
 *
 * Author: Farid Rahmani
 * Contribution: Defined the places used by the animated children's stories.
 */
public enum Backdrop {
    /** A sunny green meadow. */
    MEADOW,
    /** A meadow with a river. */
    RIVER,
    /** A night sky with stars and fireflies. */
    NIGHT,
    /** Underwater. */
    SEA,
    /** Sand, sea and waves. */
    BEACH
}
